def city_code(name: str) -> str:
    """城市名 → BOSS 城市码。未收录时抛错，避免静默搜成全国。"""
    try:
        return CITY_CODES[name]
    except KeyError:
        known = "、".join(CITY_CODES)
        raise ValueError(f"未收录城市 {name!r}，已知：{known}。请在 cities.py 补充城市码。") from None
